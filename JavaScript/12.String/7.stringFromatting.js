let first = "Amit";
let second = "Singh";

console.log(first+" "+ second);


// Template Literals 

console.log(`${first} ${second}`);

// padding 

// padStart() 

let num = "5";
console.log(num.padStart(3,"0"));


// padEnd() 

console.log(num.padEnd(3,"0"));

// Character Access 


let text = "JavA";

console.log(text.charAt(2));  // It will return value of this 2 position[index value]

// using Index value 

console.log(text[2]);

// charCodeAt() 

console.log(text.charCodeAt(3)); // it will return ASCII Value

// at() 

console.log(text.at(-1));
